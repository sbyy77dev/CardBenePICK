# ===================== 텍스트/숫자 파싱 (v4) =====================
def is_froala_footer(text: str) -> bool:
    if not text: return False
    return bool(re.search(r"Powered\s*by\s*Froala\s*Editor", text, flags=re.I | re.S))

def clean_line(text: str) -> str:
    if not text: return ""
    text = re.sub(r"Powered\s*by\s*Froala\s*Editor.*$", "", text, flags=re.I | re.S)
    text = text.replace("\xa0", " ")
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"^\s*[-•]\s*", "- ", text)
    return text

def is_bullet_like_strong(s: str) -> bool:
    if not s: return False
    st = s.strip()
    if re.match(r"^[-•*]\s*", st): return True
    if len(st) >= 40: return True
    if re.search(r"(다\.|요\.|!|\?|:)$", st): return True
    return False

def parse_amount(text: str) -> int:
    if not text: return 0
    text = text.replace(",", "").replace(" ", "")
    match = re.search(r"(\d+)(천|만)?원?", text)
    if not match: return 0
    num = int(match.group(1))
    unit = match.group(2)
    if unit == "천": num *= 1000
    elif unit == "만": num *= 10000
    return num

# ===================== 테이블 파싱 (v4) =====================
def parse_table(table_tag):
    rows = []
    for tr in table_tag.find_all("tr"):
        cells = []
        for td in tr.find_all(["td", "th"]):
            text = clean_line(td.get_text(" ", strip=True))
            if text:
                cells.append(text)
        if any(cells):
            rows.append(cells)
    return rows

