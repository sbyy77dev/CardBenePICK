# ===================== 상세 파싱 (에러 수정 버전) =====================
def parse_card_detail(html: str, card_id: str, card_type: int) -> Optional[Dict[str, Any]]:
    soup = BeautifulSoup(html, "lxml")

    # 1. [안전 장치] 카드 이름 태그 찾기
    name_tag = soup.select_one("div.data_area > div.tit > strong.card")
    # print(f"카드 이름 태그 존재 : {card_id}")

    # ⚠️ 수정된 부분: 이름 태그가 없으면(잘못된 페이지면) 바로 포기하고 None 반환
    if not name_tag:
        # print(f"🔍 ID {card_id}: 카드 이름을 찾을 수 없음 (유효하지 않은 페이지)")
        return None

    # 2. 이름 추출 및 체크카드 필터링
    raw_name = name_tag.get_text(strip=True)

    # [필터링] 이름에 '체크' 또는 'check'가 있으면 제외
    if "체크" in raw_name or "check" in raw_name.lower():
        # print(f"⛔ [Filter] ID {card_id} 제외: 체크카드임 ({raw_name})")
        return None

    # 3. 데이터 구조 초기화
    card_data = {
        "card_id": card_id,
        "card_rank": None,
        "card_link": f"{DETAIL_BASE_URL}{card_id}",
        "card_name": raw_name,  # 추출한 이름 저장
        "card_company": "정보 없음",
        "card_type": card_type,
        "domestic_year_cost": 0,
        "abroad_year_cost": 0,
        "previous_month_performance": 0,
        "benefits": [],
    }

    # 4. 회사명
    company_tag = soup.select_one("div.data_area > div.tit > p.brand")
    if company_tag:
        card_data["card_company"] = company_tag.get_text(strip=True)

    # 5. 연회비 / 전월실적 파싱
    bnf2 = soup.select_one("div.bnf2")
    if bnf2:
        for dl in bnf2.select("dl"):
            dt, dd = dl.find("dt"), dl.find("dd")
            if not dt or not dd: continue

            key, val = dt.get_text(strip=True), dd.get_text(strip=True)
            if "연회비" in key:
                domestic = abroad = 0
                for span in dd.select("span"):
                    txt = span.get_text(strip=True)
                    if "국내" in txt:
                        domestic = parse_amount(txt)
                    elif "해외" in txt:
                        abroad = parse_amount(txt)

                if domestic == 0 and abroad > 0: domestic = abroad
                if abroad == 0 and domestic > 0: abroad = domestic

                card_data["domestic_year_cost"] = domestic
                card_data["abroad_year_cost"] = abroad
            elif "전월실적" in key:
                card_data["previous_month_performance"] = parse_amount(val)

    # 6. 혜택 파싱
    for dl in soup.select("div.lst.bene_area > dl"):
        title_tag = dl.select_one("dt > p.txt1")
        summary_tag = dl.select_one("dt > i")
        content_tag = dl.select_one("dd > div.in_box")

        if not title_tag or not content_tag:
            continue

        category = title_tag.get_text(strip=True)
        summary = summary_tag.get_text(strip=True) if summary_tag else None
        benefit_obj = {"category": category, "summary": summary, "subtitles": []}

        current_subtitle = None
        current_desc = []

        def flush_sub():
            if current_subtitle or current_desc:
                benefit_obj["subtitles"].append({
                    "subtitle": current_subtitle or summary or category,
                    "descriptions": current_desc.copy()
                })
                current_desc.clear()

        for child in content_tag.children:
            if getattr(child, "name", None) == "p":
                text = child.get_text(" ", strip=True)
                if not text: continue

                # is_froala_footer 함수가 정의되어 있어야 함 (없으면 생략 가능)
                try:
                    if is_froala_footer(text): continue
                except: pass

                strong_el = child.find("strong")
                if strong_el:
                    strong_text = strong_el.get_text(strip=True)
                    flush_sub()
                    current_subtitle = strong_text
                    continue

                # clean_line 함수가 정의되어 있어야 함
                try:
                    current_desc.append(clean_line(text))
                except:
                    current_desc.append(text)

            elif getattr(child, "name", None) == "table":
                # 테이블 파싱 로직 (필요시 추가)
                pass

        flush_sub()
        card_data["benefits"].append(benefit_obj)

    return card_data

