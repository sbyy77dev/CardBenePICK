# ===================== 신규발급 중단 필터 =====================
def is_discontinued(obj: Dict[str, Any]) -> bool:
    """
    응답 JSON에서 신규발급/판매 중단을 의미하는 신호가 있으면 True를 반환합니다.
    (카드고릴라_크롤링.ipynb 로직 사용)
    """
    KEY_CANDIDATES = [
        "isIssuable", "issuable", "issueStop", "isIssueStopped",
        "applyAvailable", "applyStatus", "salesStatus",
        "serviceStatus", "status", "openStatus"
    ]
    BAD_STRINGS = {"n", "false", "0", "end", "stop", "closed", "close"}
    KOREAN_FLAGS = ["신규발급이 중단", "발급이 중단", "판매중지", "판매 중단", "단종", "종료"]

    # 1) 전형적인 상태 키 점검
    for k in KEY_CANDIDATES:
        if k in obj:
            v = obj[k]
            if isinstance(v, str):
                vs = v.strip().lower()
                if (vs in BAD_STRINGS) or any(flag in v for flag in KOREAN_FLAGS):
                    return True
            elif isinstance(v, (int, bool)):
                if v in (0, False):
                    return True

    # 2) 모든 문자열 필드에서 문구 스캔 (재귀)
    def walk(x):
        if isinstance(x, dict):
            for vv in x.values():
                if walk(vv): return True
        elif isinstance(x, list):
            for vv in x:
                if walk(vv): return True
        elif isinstance(x, str):
            s = x.strip()
            if any(flag in s for flag in KOREAN_FLAGS):
                return True
        return False

    return walk(obj)

